EXTRA = {'♪': 0x80, '☆': 0x81, '♥': 0x82, '…': 0x83}
FIRST, LAST = 0x20, 0x83
NGLYPH = LAST - FIRST + 1


def code_of(ch):
    return EXTRA.get(ch, ord(ch))


def width(ch):
    if ch == ' ':
        return SPACE_ADV
    top, rows = G[ch]
    return max(len(r) for r in rows) + 1


def text_width(s):
    return sum(width(c) for c in s)


def encodable(ch):
    return ch in G


def build():
    """-> (glyph bytes: NGLYPH x 16 row masks, LSB = leftmost px; widths: NGLYPH advances)."""
    glyphs = bytearray(NGLYPH * 16)
    widths = bytearray(NGLYPH)
    for ch, (top, rows) in G.items():
        c = code_of(ch) - FIRST
        widths[c] = width(ch)
        assert max(len(r) for r in rows) <= 8, ch
        for i, r in enumerate(rows):
            y = Y0 + top + i
            assert 0 <= y < 16, ch
            glyphs[c * 16 + y] = sum(1 << x for x, p in enumerate(r) if p == '#')
    return bytes(glyphs), bytes(widths)


